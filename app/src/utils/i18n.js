const lang = ref(uni.getStorageSync('moskill_lang') || uni.getSystemInfoSync().language?.startsWith('zh') ? 'zh' : 'en')

export function setLang(l) {
  lang.value = l
  uni.setStorageSync('moskill_lang', l)
}

export function toggleLang() {
  setLang(lang.value === 'zh' ? 'en' : 'zh')
}

export function t(key) {
  const keys = key.split('.')
  let val = messages[lang.value]
  for (const k of keys) {
    if (!val) return key
    val = val[k]
  }
  return val || key
}

export function useLang() {
  return { lang, t, setLang, toggleLang }
}

export default { lang, t, setLang, toggleLang, useLang }
